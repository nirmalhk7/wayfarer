import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const directory = fileURLToPath(new URL(".", import.meta.url));
const ranks = await readFile(new URL("../tools/county2026-game-ranks.tsv", import.meta.url), "utf8");

const result = await build({
  absWorkingDir: directory,
  entryPoints: ["trading-http.mjs"],
  outfile: "generated/trading-http.mjs",
  write: false,
  banner: { js: "// Generated by npm run bundle:vercel. Edit the shared sources." },
  bundle: true,
  platform: "node",
  target: "node24",
  tsconfigRaw: {},
  format: "esm",
  plugins: [{
    name: "embed-county-ranks",
    setup(builder) {
      builder.onLoad({ filter: /[/\\]rank-source\.mjs$/ }, () => ({
        contents: "export const rankSource = " + JSON.stringify(ranks) + ";",
        loader: "js",
      }));
    },
  }],
});

const output = new URL("generated/trading-http.mjs", import.meta.url);
const bytes = Buffer.from(result.outputFiles[0].contents);
if (process.argv.includes("--check")) {
  if (!(await readFile(output)).equals(bytes)) {
    throw new Error("Vercel bundle is stale. Run npm run bundle:vercel and commit the result.");
  }
} else {
  await mkdir(new URL("generated/", import.meta.url), { recursive: true });
  await writeFile(output, bytes);
}
